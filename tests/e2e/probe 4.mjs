import { chromium } from 'playwright';
const b = await chromium.launch(); const c = await b.newContext({ ignoreHTTPSErrors: true }); const p = await c.newPage();
await p.setViewportSize({ width: 1500, height: 1300 });
await p.goto(process.env.SPLUNK_WEB_URL + '/en-US/app/assetdb/explore', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(6000);
console.log('textboxes:', await p.getByRole('textbox').count());
const box = p.getByRole('textbox').first();
console.log(await box.evaluate(e => e.outerHTML.slice(0, 200)));
await box.fill('110.0.0.4'); await box.press('Enter');
await p.waitForTimeout(6000);
console.log((await p.locator('body').innerText()).slice(600, 1500));
console.log('tables:', await p.locator('[data-test="table"], table').count(), 'rows:', await p.getByRole('row').count());
await p.screenshot({ path: 'dist/e2e-explore.png' });
await b.close();
