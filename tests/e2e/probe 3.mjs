import { chromium } from 'playwright';
const b = await chromium.launch(); const c = await b.newContext({ ignoreHTTPSErrors: true }); const p = await c.newPage();
await p.setViewportSize({ width: 1280, height: 1600 });
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('console:', m.text().slice(0, 200)); });
p.on('pageerror', e => console.log('pageerror:', String(e).slice(0, 300)));
p.on('response', r => { if (r.status() >= 400 && /assetdb|parser|search\/jobs/.test(r.url())) console.log(r.status(), r.url().slice(0, 150)); });
await p.goto(process.env.SPLUNK_WEB_URL + '/en-US/app/assetdb/configure', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('#ab_config .lookups-table');
await p.click('#ab_config .adb-lookup-edit');
await p.waitForSelector('.modal:visible');
await p.fill('.modal:visible #inputSourceMaxAge input', '45d');
await p.fill('.modal:visible #inputSourceFilter input', 'priority>0');
await p.click('.modal:visible .btn-primary');
await p.waitForTimeout(3000);
console.log('errors:', await p.locator('.modal:visible .error-message').allInnerTexts());
console.log('modal still open:', await p.locator('.modal:visible').count());
await b.close();
