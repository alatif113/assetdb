#!/usr/bin/env python3
"""Build the vendor icon module from assets/vendors.json and the logo files in assets/vendors/.

Every source gets a vendor logo picked from keywords found in its name or lookup name (see assets/README.md). The logos are embedded in the
code, as data: URIs, so the Configure page and the visualizations (which run in iframes) need no extra requests. Outputs, committed:

    viz/shared/vendor-icons.mjs                    ES module for the visualizations (bundled by viz/build.mjs)
    appserver/static/js/src/vendor_icons.js        AMD module for the Configure page (built into vendor_icons.min.js by npm run build)

Usage: python3 scripts/build-vendor-icons.py [--check]   (--check only reports whether the committed files are current)
"""
import base64
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets"
OUT_MJS = ROOT / "viz" / "shared" / "vendor-icons.mjs"
OUT_AMD = ROOT / "appserver" / "static" / "js" / "src" / "vendor_icons.js"

HEADER = ("// GENERATED by scripts/build-vendor-icons.py from assets/vendors.json and assets/vendors/. Do not edit.\n"
          "// Picks the logo of a source from keywords in its name or lookup name. The logos are the property of their owners and are used only to\n"
          "// identify the product a source comes from.\n")

# A neutral glyph for a source that matches no vendor (the default "other" icon).
DEFAULT_GLYPH = ('<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
                 '<ellipse cx="12" cy="6" rx="8" ry="3"/><path d="M4 6v6c0 1.7 3.6 3 8 3s8-1.3 8-3V6M4 12v6c0 1.7 3.6 3 8 3s8-1.3 8-3v-6"/></svg>')

BODY = r"""
const lc = (t) => String(t == null ? '' : t).toLowerCase();
/** `crowdstrike_devices.csv` -> ' crowdstrike devices csv ' (words) and 'crowdstrikedevicescsv' (squashed, for long keywords). */
function norm(text) { const w = lc(text).replace(/[^a-z0-9]+/g, ' ').trim(); return { words: ' ' + w + ' ', flat: w.replace(/ /g, '') }; }
/** The vendor whose keywords appear in the text (a source name, a lookup name, or both joined), or null. The order of VENDORS is the priority. */
function vendorFor(text) {
	const n = norm(text); if (!n.flat) return null;
	for (let i = 0; i < VENDORS.length; i++) {
		const v = VENDORS[i];
		if (v.sub.some((k) => n.flat.indexOf(k) >= 0) || v.word.some((k) => n.words.indexOf(k) >= 0)) return v;
	}
	return null;
}
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
/**
 * The icon for a source as HTML: the vendor's logo as an <img>, or the neutral glyph when no vendor matches. `theme` is 'dark' or 'light';
 * `px` is the size. Logos that vanish on a dark background sit on a small light chip there.
 */
function vendorIcon(v, theme, px) {
	const size = px || 16;
	if (!v) return '<span class="vicon vdefault" style="display:inline-flex;width:' + size + 'px;height:' + size + 'px;flex:none;color:currentColor;opacity:.7" title="Other source" aria-hidden="true">' + DEFAULT_GLYPH + '</span>';
	const dark = theme === 'dark', src = (dark && v.dark) || v.light, chip = dark && v.chip;
	return '<img class="vicon" src="' + src + '" width="' + size + '" height="' + size + '" alt="" title="' + attr(v.name) + '" style="flex:none;object-fit:contain;' + (chip ? 'background:#e6ebef;border-radius:3px;padding:1px;box-sizing:border-box;' : '') + '">';
}
"""


def data_uri(path: Path) -> str:
    raw = path.read_bytes()
    if path.suffix == ".svg":
        text = raw.decode("utf-8", "replace")
        text = text[text.index("<svg"):]
        text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
        text = re.sub(r">\s+<", "><", text).strip()
        return "data:image/svg+xml," + quote(text, safe="/:=;,()' @-_.!~*")  # percent-encode only what a URL needs
    if path.suffix == ".png":
        return "data:image/png;base64," + base64.b64encode(raw).decode()
    raise SystemExit(f"unsupported logo type: {path}")


def flat(k):
    return re.sub(r"[^a-z0-9]", "", k.lower())


def build():
    vendors = json.loads((SRC / "vendors.json").read_text())
    out = []
    for v in vendors:
        sub = [flat(k) for k in v["keywords"] if len(flat(k)) >= 6]
        word = [" " + re.sub(r"[^a-z0-9]+", " ", k.lower()).strip() + " " for k in v["keywords"] if len(flat(k)) < 6]
        e = {"id": v["id"], "name": v["name"], "sub": sub, "word": word, "light": data_uri(SRC / "vendors" / v["light"])}
        light = SRC / "vendors" / v["light"]
        dark = light.with_name(light.stem + ".dark" + light.suffix)   # an optional variant for dark backgrounds
        if dark.exists():
            e["dark"] = data_uri(dark)
        if v.get("chip"):
            e["chip"] = True
        out.append(e)
    data = "const DEFAULT_GLYPH = " + json.dumps(DEFAULT_GLYPH) + ";\nconst VENDORS = [\n" + ",\n".join("\t" + json.dumps(e, separators=(",", ":")) for e in out) + "\n];\n"
    exports = "VENDORS, vendorFor, vendorIcon, DEFAULT_GLYPH"
    mjs = HEADER + data + BODY + "export { " + exports + " };\n"
    amd = HEADER + "define([], function () {\n" + data + BODY + "\treturn { VENDORS: VENDORS, vendorFor: vendorFor, vendorIcon: vendorIcon, DEFAULT_GLYPH: DEFAULT_GLYPH };\n});\n"
    return {OUT_MJS: mjs, OUT_AMD: amd}


if __name__ == "__main__":
    files = build()
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in files.items() if not p.exists() or p.read_text() != t]
        if stale:
            sys.exit("out of date: " + ", ".join(stale) + "\nRun: python3 scripts/build-vendor-icons.py")
        print("vendor icons are current")
    else:
        for p, t in files.items():
            p.write_text(t)
            print("wrote", p.relative_to(ROOT), len(t), "bytes")
